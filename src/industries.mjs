/** 单个行业值 → 规范名称；纯数字等无意义的值归为“其他”。 */
export function normalizeIndustry(value) {
  const text = String(value ?? '').trim().replace(/／/g, '/').replace(/\s*\/\s*/g, '/');
  if (!text || /^\d+$/.test(text)) return '其他';
  return ALIASES.get(text) || text;
}
